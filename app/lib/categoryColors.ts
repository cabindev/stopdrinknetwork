// กำหนดตายตัวรายหมวด แต่ละสีต้องแยกจากกันชัดเจน และไม่ใช้โทนส้ม (ส้ม = สีแบรนด์/หมุดรวมจังหวัด)
export const CATEGORY_COLOR_MAP: Record<string, string> = {
  'Civic Space': '#eab308', // เหลือง
  'งานสื่อสาร': '#2563eb', // น้ำเงิน
  'ชุมชนหัวใจเพชร': '#dc2626', // แดง
  'เฝ้าระวังและบังคับใช้กฎหมาย': '#475569', // เทาเข้ม
  'ปฐมวัย': '#ec4899', // ชมพู
  'โรงเรียนคำพ่อสอน': '#7c3aed', // ม่วง
  'โพธิสัตว์น้อย': '#16a34a', // เขียว
  'ครูดีไม่มีอบายมุข': '#92400e', // น้ำตาล
  'งานบุญประเพณี': '#c026d3', // ม่วงแดง
  'พื้นที่สร้างสรรค์': '#84cc16', // เขียวมะนาว
  'เยาวชนระดับอำเภอ': '#0d9488', // เขียวหัวเป็ด
  'Futsal SDN': '#06b6d4', // ฟ้า
  'เครือข่ายพระสงฆ์นักพัฒนา': '#1e3a8a', // กรมท่า
};

// สีสำรองสำหรับหมวดใหม่ที่แอดมินเพิ่มภายหลัง — คนละโทนกับชุดหลัก
export const FALLBACK_COLORS = ['#9f1239', '#3f6212', '#5b21b6', '#155e75', '#713f12', '#334155'];

// สร้างฟังก์ชันหาสีจากรายชื่อหมวด (หมวดใหม่ไล่หยิบสีสำรองไม่ให้ซ้ำกัน)
export function makeColorOf(categories: string[]) {
  const m = new Map<string, string>();
  let fallbackIdx = 0;
  for (const c of categories) {
    m.set(c, CATEGORY_COLOR_MAP[c] ?? FALLBACK_COLORS[fallbackIdx++ % FALLBACK_COLORS.length]);
  }
  return (category: string) => m.get(category) ?? '#334155';
}

// หาสีเดี่ยว ๆ โดยไม่ต้องมีรายชื่อทั้งหมด (ใช้ตอนแสดงผลรายการที่รู้ชื่อหมวดอยู่แล้ว)
export const categoryColor = (name: string) => CATEGORY_COLOR_MAP[name] ?? '#334155';
