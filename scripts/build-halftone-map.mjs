// scripts/build-halftone-map.mjs — แผนที่จุด halftone ประเทศไทย + เพื่อนบ้าน สำหรับหน้าแรก
//   → public/maps/thailand-halftone.svg (ฐานแผนที่ — นิ่ง) + app/data/halftoneGrid.json (กรอบ/ระยะจุด ให้ server ปักจุดงานลงตาราง)
// แนวเดียวกับ parliament/scripts/build-halftone-map.mjs แต่ไทยใช้ขอบเขตชุดเดียวกับแผนที่เรา (thailand-outline.json)
// รันครั้งเดียว (ผลลัพธ์ commit ไว้): node scripts/build-halftone-map.mjs — แก้ค่าในนี้แล้วต้องรันใหม่ทั้งคู่
import fs from 'fs';
import { createRequire } from 'module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const world = require('world-atlas/countries-50m.json');
const thailand = JSON.parse(fs.readFileSync('app/data/thailand-outline.json', 'utf8')).geometry;
const countries = feature(world, world.objects.countries).features.filter((f) => f.geometry && f.properties.name !== 'Thailand');

// กรอบ: ไทยเต็มกรอบ เห็นเพื่อนบ้านรอบ ๆ — แนวตั้ง เพราะไทยสูงกว่ากว้าง (วางคอลัมน์ขวาของหน้าแรก)
const LON0 = 94.6, LON1 = 108.4, LAT0 = 4.6, LAT1 = 21.2;
const W = 1000;
const K = Math.cos((13 * Math.PI) / 180); // ปรับสัดส่วนแนวนอนที่ละติจูดไทย
const H = Math.round((W * (LAT1 - LAT0)) / ((LON1 - LON0) * K));
const S = 12; // ระยะจุด (หน่วย viewBox) ≈ 18 กม. — หยาบพอที่จุดงานไม่บอกตำแหน่งจริง
const toLon = (x) => LON0 + (x / W) * (LON1 - LON0);
const toLat = (y) => LAT1 - (y / H) * (LAT1 - LAT0);
const TH_CENTER = [100.9, 13.5];

function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function inGeometry(lon, lat, g) {
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  return polys.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h)));
}
function bbox(g) {
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  let a = [Infinity, Infinity, -Infinity, -Infinity];
  for (const p of polys) for (const [x, y] of p[0]) a = [Math.min(a[0], x), Math.min(a[1], y), Math.max(a[2], x), Math.max(a[3], y)];
  return a;
}
const neighbours = countries
  .map((f) => ({ geometry: f.geometry, box: bbox(f.geometry) }))
  .filter(({ box }) => box[2] >= LON0 && box[0] <= LON1 && box[3] >= LAT0 && box[1] <= LAT1);
const thBox = bbox(thailand);

const dot = (x, y, r) => `M${(x - r).toFixed(1)} ${y.toFixed(1)}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
let th = '', near = '', nTh = 0;
// ตารางหกเหลี่ยม (แถวเยื้องกัน) — สูตรเดียวกับ snapToGrid() ใน app/lib/halftoneMap.ts
for (let row = 0, y = S / 2; y < H; row++, y += S * 0.866) {
  for (let x = (row % 2 ? S / 2 : 0) + S / 2; x < W; x += S) {
    const lon = toLon(x), lat = toLat(y);
    if (lon >= thBox[0] && lon <= thBox[2] && lat >= thBox[1] && lat <= thBox[3] && inGeometry(lon, lat, thailand)) {
      th += dot(x, y, 3.6);
      nTh++;
    } else if (neighbours.some((c) => lon >= c.box[0] && lon <= c.box[2] && lat >= c.box[1] && lat <= c.box[3] && inGeometry(lon, lat, c.geometry))) {
      // เล็กลงตามระยะจากไทย ให้ไทยเด่น
      const d = Math.hypot((lon - TH_CENTER[0]) * K, lat - TH_CENTER[1]);
      near += dot(x, y, +Math.max(1, 2.4 - d * 0.12).toFixed(2));
    }
  }
}

// สีจุดโทนเทาบนพื้นขาว — ส้มสงวนให้ "จุดที่มีงาน" ที่หน้าเว็บวาดทับ
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" aria-hidden="true">
<!-- Halftone map: Thailand + neighbours. Data: Natural Earth (public domain) via world-atlas + app/data/thailand-outline.json. Generated by scripts/build-halftone-map.mjs -->
<path fill="#ececec" d="${near}"/>
<path fill="#c7c7c7" d="${th}"/>
</svg>
`;
fs.mkdirSync('public/maps', { recursive: true });
fs.writeFileSync('public/maps/thailand-halftone.svg', svg);
fs.writeFileSync('app/data/halftoneGrid.json', JSON.stringify({ W, H, S, LON0, LON1, LAT0, LAT1 }) + '\n');
console.log(`✓ public/maps/thailand-halftone.svg ${W}×${H} · Thailand ${nTh} dots · ${(svg.length / 1024).toFixed(0)} KB`);
